"""Regenerate the README metrics table from the JSON artefacts.

Usage: python scripts/update_readme_metrics.py [--check]
--check exits 1 when the README table is out of date (used by CI).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START = "<!-- METRICS:START -->"
END = "<!-- METRICS:END -->"


def load(rel: str):
    path = ROOT / rel
    if not path.exists():
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def build_table() -> str:
    history = load("data/training_history.json") or {}
    critic = load("data/critic_metrics.json") or {}
    composition = load("data/composition_metrics.json") or {}
    temporal = load("data/temporal_metrics.json") or {}
    # Newest benchmark run wins; the Tier-C baseline file stays untouched.
    runs = sorted(
        (ROOT / "data/benchmarks").glob("benchmark_results*.json"), key=lambda f: f.stat().st_mtime
    )
    benchmark = load(str(runs[-1].relative_to(ROOT))) if runs else {}
    summary = benchmark.get("summary", benchmark)

    val_acc = ""
    if history.get("token_accuracy_history"):
        val_acc = f"{history['token_accuracy_history'][-1]['val_accuracy']:.2f}%"

    rows = [
        ("SVAN Action Transformer", history.get("parameters"),
         f"val loss {history.get('best_val_loss', 'n/a')}, token acc {val_acc or 'n/a'}",
         f"{history.get('train_samples', 'n/a')} train / {history.get('total_epochs', 'n/a')} epochs"),
        ("Neural Visual Critic", 368044,
         f"val F1 {critic.get('best_f1', 'n/a')}, precision {critic.get('precision', 'n/a')}",
         f"{critic.get('train_samples', 'n/a')} train / {critic.get('total_epochs', 'n/a')} epochs"),
        ("TemporalSVAN", temporal.get("parameter_count"),
         f"best val loss {temporal.get('best_val_loss', 'n/a')}",
         f"{temporal.get('train_samples', 'n/a')} train / {temporal.get('epochs', 'n/a')} epochs"),
        ("SocketPredictor", composition.get("parameter_count"),
         f"final pixel error {composition.get('final_pixel_error', 'n/a')}",
         f"{composition.get('epochs', 'n/a')} epochs"),
    ]

    lines = [
        START,
        "_Generated by `python scripts/update_readme_metrics.py` from `data/*.json`. Do not edit by hand._",
        "",
        "| Model | Parameters | Quality | Training |",
        "| --- | --- | --- | --- |",
    ]
    for name, params, quality, train in rows:
        p = f"{int(params):,}" if isinstance(params, (int, float)) else "n/a"
        lines.append(f"| {name} | {p} | {quality} | {train} |")

    trained = summary.get("trained_model") if isinstance(summary, dict) else None
    if trained:
        lines += [
            "",
            f"Benchmark ({summary.get('total_prompts', '?')} held-out prompts, "
            f"{summary.get('timestamp', 'unknown time')}): trained model "
            f"IoU {trained.get('avg_silhouette_iou')}, "
            f"valid actions {trained.get('avg_valid_action_rate')}%, "
            f"palette adherence {trained.get('avg_palette_adherence')}%, "
            f"latency {trained.get('avg_latency_ms')} ms.",
        ]
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    text = README.read_text(encoding="utf-8")
    table = build_table()
    if START not in text or END not in text:
        print(f"README is missing {START} / {END} markers", file=sys.stderr)
        return 2

    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    updated = head + table + tail

    if "--check" in sys.argv:
        if updated != text:
            print("README metrics are stale; run python scripts/update_readme_metrics.py")
            return 1
        print("README metrics are up to date")
        return 0

    README.write_text(updated, encoding="utf-8")
    print("README metrics updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
