"""Regenerate the README metrics table from the JSON artefacts.

Usage: python scripts/update_readme_metrics.py [--check]
--check exits 1 when the README table is out of date (used by CI).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START = "<!-- METRICS:START -->"
END = "<!-- METRICS:END -->"


def _run_order(path: Path):
    """Sort key: the run's own timestamp, with mtime only as a tie-break."""
    try:
        data = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        data = {}
    stamp = data.get("timestamp") or data.get("summary", {}).get("timestamp") or ""
    return (str(stamp), path.stat().st_mtime)


def load(rel: str):
    path = ROOT / rel
    if not path.exists():
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def build_table() -> str:
    history = load("data/training_history.json") or {}
    critic = load("data/critic_metrics.json") or {}
    composition = load("data/composition_metrics.json") or {}
    temporal = load("data/temporal_metrics.json") or {}
    # Newest benchmark run wins; the Tier-C baseline file stays untouched. The
    # timestamp inside the file decides, because checkout order decides mtimes
    # and a fresh clone would otherwise publish an older run than a dev machine.
    runs = sorted(
        (ROOT / "data/benchmarks").glob("benchmark_results*.json"), key=_run_order
    )
    benchmark = load(str(runs[-1].relative_to(ROOT))) if runs else {}
    summary = benchmark.get("summary", benchmark)

    val_acc = ""
    if history.get("token_accuracy_history"):
        val_acc = f"{history['token_accuracy_history'][-1]['val_accuracy']:.2f}%"

    rows = [
        ("SVAN Action Transformer", history.get("parameters"),
         f"val loss {history.get('best_val_loss', 'n/a')}, token acc {val_acc or 'n/a'}",
         f"{history.get('train_samples', 'n/a')} train / {history.get('total_epochs', 'n/a')} epochs"),
        ("Neural Visual Critic", critic.get("parameter_count", 368044),
         f"val F1 {critic.get('best_f1', 'n/a')}, recall {critic.get('recall', 'n/a')}% "
         f"(calibrated p={critic.get('calibrated_threshold', 'n/a')}: "
         f"{critic.get('calibrated_precision', 'n/a')}% precision @ {critic.get('calibrated_false_positive_rate', 'n/a')}% FP)",
         f"{critic.get('train_samples', 'n/a')} train / {critic.get('total_epochs', 'n/a')} epochs"),
        ("TemporalSVAN", temporal.get("parameter_count"),
         f"best val loss {temporal.get('best_val_loss', 'n/a')}"
         + (f" (epoch {temporal['best_epoch']})" if temporal.get("best_epoch") else ""),
         f"{temporal.get('train_samples', 'n/a')} train / {temporal.get('epochs', 'n/a')} epochs"),
        ("SocketPredictor", composition.get("parameter_count"),
         f"final pixel error {composition.get('final_pixel_error', 'n/a')}",
         f"{composition.get('epochs', 'n/a')} epochs"),
    ]

    lines = [
        START,
        "_Generated by `python scripts/update_readme_metrics.py` from `data/*.json`. Do not edit by hand._",
        "",
        "| Model | Parameters | Quality | Training |",
        "| --- | --- | --- | --- |",
    ]
    for name, params, quality, train in rows:
        p = f"{int(params):,}" if isinstance(params, (int, float)) else "n/a"
        lines.append(f"| {name} | {p} | {quality} | {train} |")

    trained = summary.get("trained_model") if isinstance(summary, dict) else None
    if trained:
        lines += [
            "",
            f"Legacy proxy benchmark ({summary.get('total_prompts', '?')} prompts, "
            f"{summary.get('timestamp', 'unknown time')}; **not** image-grounded, see "
            "`docs/IMPLEMENTATION_AUDIT.md`): "
            f"density surrogate {trained.get('avg_silhouette_iou')}, "
            f"render-error rate {trained.get('avg_valid_action_rate')}%, "
            f"colour faithfulness {trained.get('avg_colour_faithfulness')}% "
            f"({trained.get('colours_present_rate')}% of prompts get their colour), "
            f"latency {trained.get('avg_latency_ms')} ms.",
        ]

    grounded = load("data/benchmarks/neural_vs_procedural.json") or {}
    trained_arm = (grounded.get("results") or {}).get("trained_best4")
    base_arm = (grounded.get("results") or {}).get("procedural_baseline")
    if trained_arm and base_arm:
        t, b = trained_arm["summary"], base_arm["summary"]
        lines += [
            "",
            f"Pixel-grounded benchmark ({t['n']} prompts, seed {grounded.get('seed', 'n/a')}; "
            "`silhouette_iou` against the canonical template, palette membership counted per pixel): "
            f"trained model (best_of=4) IoU {t['silhouette_iou']['mean']:.3f}, "
            f"palette {t['palette_adherence_pct']['mean']:.1f}%, "
            f"colour faithfulness {t['colour_faithfulness']['mean']:.1f}%, "
            f"{t['latency_ms']['mean']:.0f} ms vs procedural baseline IoU "
            f"{b['silhouette_iou']['mean']:.3f}, palette "
            f"{b['palette_adherence_pct']['mean']:.1f}%, colour "
            f"{b['colour_faithfulness']['mean']:.1f}%, {b['latency_ms']['mean']:.1f} ms.",
        ]
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    text = README.read_text(encoding="utf-8")
    table = build_table()
    if START not in text or END not in text:
        print(f"README is missing {START} / {END} markers", file=sys.stderr)
        return 2

    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    updated = head + table + tail

    if "--check" in sys.argv:
        if updated != text:
            print("README metrics are stale; run python scripts/update_readme_metrics.py")
            return 1
        print("README metrics are up to date")
        return 0

    README.write_text(updated, encoding="utf-8")
    print("README metrics updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
